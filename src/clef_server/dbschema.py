"""Table definitions (SQLAlchemy Core). Mirrors the Alembic migrations in ``migrations/versions``.

The logical DDL is in docs/ARCHITECTURE.md (Storage). Timestamps are DOUBLE PRECISION unix seconds, days are
TEXT 'YYYY-MM-DD' (UTC), booleans are INTEGER 0/1 and JSON is TEXT. Identity columns are ``INTEGER PRIMARY KEY
AUTOINCREMENT`` on SQLite and ``BIGINT GENERATED BY DEFAULT AS IDENTITY`` on Postgres.

A unit test (tests/unit/test_db.py) compares this metadata with a freshly migrated database: change both.
"""

from __future__ import annotations

from sqlalchemy import (
    BigInteger,
    Column,
    Double,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    PrimaryKeyConstraint,
    Table,
    Text,
    func,
    text,
)

metadata = MetaData()

# INTEGER on SQLite (only `INTEGER PRIMARY KEY` can be AUTOINCREMENT), BIGINT IDENTITY on Postgres.
IdentityInt = BigInteger().with_variant(Integer(), "sqlite")


def _identity(name: str) -> Column:
    return Column(name, IdentityInt, Identity(always=False), primary_key=True)


# ---------------------------------------------------------------- 0001_baseline (jobs, as in v3.1)

jobs = Table(
    "jobs",
    metadata,
    _identity("seq"),
    Column("id", Text, nullable=False, unique=True),
    Column("kind", Text, nullable=False),
    Column("status", Text, nullable=False),
    Column("owner", Text),
    Column("payload", Text, nullable=False),
    Column("metadata", Text),
    Column("webhook", Text),
    Column("deliveries", Text, nullable=False, server_default=text("'{}'")),
    Column("total", Integer),
    Column("done", Integer, nullable=False, server_default=text("0")),
    Column("failed", Integer, nullable=False, server_default=text("0")),
    Column("created_at", Double, nullable=False),
    Column("started_at", Double),
    Column("finished_at", Double),
    Column("run_started_at", Double),
    Column("run_base_done", Integer, nullable=False, server_default=text("0")),
    Column("resumes", Integer, nullable=False, server_default=text("0")),
    Column("cancel_requested", Integer, nullable=False, server_default=text("0")),
    Column("error", Text),
    Column("result", Text),
    Column("idem_key", Text),
    # ---- 0002_v32
    Column("model", Text),  # C1: "id@revision" served at submit
    Column("priority", Integer, nullable=False, server_default=text("1")),  # E1
    Column("schedule", Text),  # E1: JSON {"window", "tz"}
    Column("expire_after_s", Double),  # E1
    Column("eligible_at", Double),  # E1
    Column("quota_day", Text),  # E1
    Column("quota_reserved", BigInteger, nullable=False, server_default=text("0")),  # E1
    Column("tokens", BigInteger, nullable=False, server_default=text("0")),  # E1
    # ---- 0003_job_hits
    Column(
        "hits", BigInteger, nullable=False, server_default=text("0")
    ),  # cache hits handed back to the quota
    sqlite_autoincrement=True,
)
Index("jobs_status", jobs.c.status, jobs.c.seq)
Index(
    "jobs_idem",
    func.coalesce(jobs.c.owner, text("''")),
    jobs.c.idem_key,
    unique=True,
    sqlite_where=jobs.c.idem_key.isnot(None),
    postgresql_where=jobs.c.idem_key.isnot(None),
)

items = Table(
    "items",
    metadata,
    Column("job_id", Text, ForeignKey("jobs.id", ondelete="CASCADE"), nullable=False),
    Column("idx", Integer, nullable=False),
    Column("data", Text, nullable=False),
    PrimaryKeyConstraint("job_id", "idx"),
    sqlite_with_rowid=False,
)

